#!/usr/bin/env node
// Generates the checked-in Spanish exercise-name pack. This runs only when the
// catalogue changes; the application never calls a translation service at runtime.

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { EXDB } from '../frontend/src/lib/exercises-data.js'
import existingNames from '../frontend/src/exercise-names/es.js'
import { normalizeExerciseName, OVERRIDES } from './exercise-names/es-glossary.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'frontend', 'src', 'exercise-names', 'es.js')
const endpoint = 'https://translate.googleapis.com/translate_a/single'
const batchSize = 20

const fromCurrent = process.argv.includes('--from-current')

const translateBatch = async entries => {
  const text = entries.map(([id, name]) => `${name}\n[[OPENGYM_SPLIT_${id}]]`).join('\n')
  const url = new URL(endpoint)
  url.searchParams.set('client', 'gtx')
  url.searchParams.set('sl', 'en')
  url.searchParams.set('tl', 'es')
  url.searchParams.set('dt', 't')
  url.searchParams.set('q', text)
  const res = await fetch(url)
  if (!res.ok) throw new Error(`Translation request failed: HTTP ${res.status}`)
  const data = await res.json()
  const translated = data?.[0]?.map(part => part[0]).join('') || ''
  const names = {}
  const segments = translated.split(/\n?\[\[OPENGYM_SPLIT_(\d+)\]\]\n?/)
  for (let i = 1; i < segments.length; i += 2) {
    const id = segments[i]
    const name = segments[i - 1].trim()
    if (id && name) names[id] = name
  }
  if (Object.keys(names).length !== entries.length) {
    throw new Error(`Translation response was incomplete (${Object.keys(names).length}/${entries.length})`)
  }
  return names
}

const names = {}
if (fromCurrent) {
  EXDB.forEach(ex => { names[ex.id] = existingNames[ex.id] || ex.n })
  console.log(`Normalized current catalogue: ${EXDB.length}/${EXDB.length}`)
} else {
  for (let i = 0; i < EXDB.length; i += batchSize) {
    const translated = await translateBatch(EXDB.slice(i, i + batchSize).map(ex => [ex.id, ex.n]))
    Object.assign(names, translated)
    console.log(`Translated ${Math.min(i + batchSize, EXDB.length)}/${EXDB.length}`)
  }
}
Object.assign(names, OVERRIDES)
Object.keys(names).forEach(id => { names[id] = normalizeExerciseName(names[id]) })

writeFileSync(out, `// Generated by scripts/build-exercise-names.mjs — do not edit\nexport default ${JSON.stringify(names)}\n`)
console.log(`Wrote ${out}: ${Object.keys(names).length} exercises`)
